    CONVERT(CHAR(64), HASHBYTES('SHA2_256', @salt + CAST(a.nhs_number AS VARBINARY(10))), 2) AS patient_pseudo_id,
    LEFT(a.postcode, CHARINDEX(' ', a.postcode + ' ') - 1) AS postcode_district,
    a.gp_practice_code,
    a.ethnic_code
INTO #src
