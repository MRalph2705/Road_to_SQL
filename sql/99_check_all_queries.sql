    SELECT s.*, ROW_NUMBER() OVER (PARTITION BY s.nhs_number ORDER BY s.arrival_dttm DESC, s.attendance_id DESC) AS rn
    FROM #silver_attendance AS s
    WHERE s.nhs_status = 'Valid' AND s.arrival_dttm IS NOT NULL
